require('dotenv').config({ quiet: true })
const pool = require('./src/config/db')
const { roleService } = require('./src/services/role.service')
;(async () => {
  const perms = JSON.parse(process.argv[2])
  const roles = await roleService.list(pool)
  const r = roles.find((x) => x.name === 'Thử nghiệm xem thuyền viên')
  await roleService.savePermissions(pool, [{ id: r.id, permissions: perms, scopes: r.scopes }])
  console.log('perms now', perms.join(','))
  await pool.end()
})().catch((e) => { console.error(e.message); process.exit(1) })
