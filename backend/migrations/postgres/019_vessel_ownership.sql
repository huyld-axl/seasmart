-- Existing ownership has no known start date; subsequent changes are recorded atomically.
CREATE TABLE vessel_ownership (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  vessel_id integer NOT NULL REFERENCES vessel(id),
  ship_owner_id integer NOT NULL REFERENCES ship_owner(id),
  started_at timestamptz,
  ended_at timestamptz,
  CHECK (ended_at IS NULL OR started_at IS NULL OR ended_at >= started_at)
);
CREATE UNIQUE INDEX vessel_ownership_current ON vessel_ownership(vessel_id) WHERE ended_at IS NULL;
CREATE INDEX vessel_ownership_owner ON vessel_ownership(ship_owner_id, vessel_id);
INSERT INTO vessel_ownership (vessel_id, ship_owner_id)
SELECT id, ship_owner_id FROM vessel WHERE ship_owner_id IS NOT NULL;
CREATE FUNCTION track_vessel_ownership() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP = 'UPDATE' THEN
    IF NEW.ship_owner_id IS NOT DISTINCT FROM OLD.ship_owner_id THEN RETURN NEW; END IF;
    UPDATE vessel_ownership SET ended_at = CURRENT_TIMESTAMP WHERE vessel_id = NEW.id AND ended_at IS NULL;
  END IF;
  IF NEW.ship_owner_id IS NOT NULL THEN
    INSERT INTO vessel_ownership (vessel_id, ship_owner_id, started_at) VALUES (NEW.id, NEW.ship_owner_id, CURRENT_TIMESTAMP);
  END IF;
  RETURN NEW;
END;
$$;
CREATE TRIGGER vessel_ownership_changed AFTER INSERT OR UPDATE OF ship_owner_id ON vessel
FOR EACH ROW EXECUTE FUNCTION track_vessel_ownership();
