-- Máy nhân viên đã ghép với máy chính (docs/mcah-ke-hoach-desktop-gd3.md 3.2). Mỗi bản cài có install_id riêng.
-- Mã thiết bị chỉ giữ SHA-256. Máy bị Gỡ xin vào lại thì chờ quản trị duyệt (status pending).
CREATE TABLE IF NOT EXISTS office_device (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  install_id UUID NOT NULL UNIQUE,
  name TEXT NOT NULL,
  os TEXT,
  app_version TEXT,
  token_hash TEXT,
  pair_secret_hash TEXT,
  status TEXT NOT NULL CHECK (status IN ('active', 'pending', 'removed', 'rejected')),
  requested_by INTEGER REFERENCES "user"(id),
  last_user_id INTEGER REFERENCES "user"(id),
  last_ip TEXT,
  last_seen_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  removed_at TIMESTAMPTZ,
  removed_by INTEGER REFERENCES "user"(id)
);
CREATE INDEX IF NOT EXISTS office_device_token ON office_device (token_hash);
