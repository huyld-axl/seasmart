-- Kho tệp (docs/mcah-ke-hoach-desktop-gd4.md 3.1, 3.2). Các cột đường dẫn cũ giữ nguyên tên nhưng lưu "mã tệp":
--   hs:<đường tương đối>  tệp trong thư mục hồ sơ dễ đọc (app máy tính, MCAH_FILES_DIR)
--   u:<đường tương đối>   tệp nội bộ trong UPLOAD_DIR (ảnh trang, ảnh thu nhỏ, bản gốc nhiều giấy, thùng rác; bản web: mọi tệp)
-- Đường dẫn tuyệt đối / "/uploads/..." của dữ liệu cũ vẫn đọc được (file_store.abs).
CREATE TABLE IF NOT EXISTS stored_file (
  ref TEXT PRIMARY KEY,
  sha256 TEXT NOT NULL,
  size BIGINT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS stored_file_sha ON stored_file (sha256);

-- Chuyển tệp trong thư mục hồ sơ (đổi tên thuyền viên, bản cũ…): ghi trước khi chuyển; đọc không thấy ở chỗ mới thì
-- thử chỗ cũ; job làm lại các dòng chưa xong.
CREATE TABLE IF NOT EXISTS file_move (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  from_ref TEXT NOT NULL,
  to_ref TEXT NOT NULL,
  done_at TIMESTAMPTZ,
  error TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS file_move_to ON file_move (to_ref) WHERE done_at IS NULL;

-- Hàng đợi sắp lại thư mục hồ sơ của một chủ (thuyền viên / đối tác) sau khi hồ sơ đổi.
CREATE TABLE IF NOT EXISTS file_relayout (
  owner_type TEXT NOT NULL,
  owner_id INTEGER NOT NULL,
  queued_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  PRIMARY KEY (owner_type, owner_id)
);

