const authRoutes = require('./auth.routes')
const seafarerRoutes = require('./seafarer.routes')
const { seafarerContactRoutes } = require('./seafarer.routes')
const importRoutes = require('./import.routes')
const lookupRoutes = require('./lookup.routes')
const certificateRoutes = require('./certificate.routes')
const masterDataRoutes = require('./master_data.routes')
const fleetRoutes = require('./fleet.routes')
const usersRoutes = require('./users')
const roleRoutes = require('./role.routes')
const notificationRoutes = require('./notification.routes')
const { exportPackRoutes } = require('./export_pack.routes')
const documentRoutes = require('./document.routes')
const voyageRoutes = require('./voyage.routes')
const seafarerContractRoutes = require('./seafarer_contract.routes')
const dashboardRoutes = require('./dashboard.routes')
const contractBillRoutes = require('./contract_bill.routes')
const { seafarerSeaServiceRoutes, seaServiceRoutes } = require('./sea_service.routes')

async function v1Routes(fastify) {
  fastify.register(authRoutes, { prefix: '/auth' })
  fastify.register(seafarerRoutes, { prefix: '/seafarers' })
  fastify.register(seafarerContactRoutes, { prefix: '/seafarers/:seafarerId/contacts' })
  fastify.register(importRoutes, { prefix: '/import' })
  fastify.register(lookupRoutes, { prefix: '/lookup' })
  fastify.register(certificateRoutes, { prefix: '/seafarers/:seafarerId/certificates' })
  fastify.register(masterDataRoutes, { prefix: '/admin/master' })
  fastify.register(fleetRoutes, { prefix: '/admin/master' })
  fastify.register(usersRoutes, { prefix: '/users' })
  fastify.register(roleRoutes, { prefix: '/roles' })
  fastify.register(notificationRoutes, { prefix: '/notifications' })
  fastify.register(exportPackRoutes, { prefix: '/exports' })
  fastify.register(documentRoutes, { prefix: '/documents' })
  fastify.register(seafarerSeaServiceRoutes, { prefix: '/seafarers/:seafarerId/sea-services' })
  fastify.register(seaServiceRoutes, { prefix: '/sea-services' })
  fastify.register(voyageRoutes, { prefix: '/voyages' })
  fastify.register(seafarerContractRoutes, { prefix: '/contracts' })
  fastify.register(contractBillRoutes, { prefix: '/bills' })
  fastify.register(dashboardRoutes, { prefix: '/dashboard' })
}

module.exports = v1Routes
